import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, appendFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { CodexBridge } from '../src/codex.js';
import { rounds, exportMarkdown } from '../src/report.js';
import { AuditLog, verify } from '../src/audit.js';

test('real spawned children share root audit, preserve identities, exclude inherited history and internal workers', () => {
 const dir = mkdtempSync(path.join(tmpdir(), 'codex-children-'));
 try {
  const sessions=path.join(dir,'sessions'); mkdirSync(sessions);
  const workspace=path.join(dir,'project'), audit=new AuditLog(path.join(dir,'logs')), events=[], ended=[];
  const now=Date.now()+2000;
  const row=(type,payload,at=now)=>JSON.stringify({timestamp:new Date(at).toISOString(),type,payload})+'\n';
  const opts={dir:sessions,workspace,stateFile:path.join(dir,'cursor.json'),audit,emit:e=>events.push(e),onRoundEnd:s=>ended.push(s)};
  let bridge=new CodexBridge(opts); bridge.poll();
  writeFileSync(path.join(sessions,'root.jsonl'),row('session_meta',{id:'root',cwd:workspace,source:'vscode',thread_source:'user'})+row('event_msg',{type:'task_started',turn_id:'root-turn'}));
  bridge.poll();
  const spawn=(id,role,source='subagent')=>row('session_meta',{id,session_id:'root',parent_thread_id:'root',cwd:workspace,timestamp:new Date(now).toISOString(),thread_source:source,source:{subagent:{thread_spawn:{parent_thread_id:'root',agent_path:`/root/${role}`}}}});
  const work=(id)=>row('event_msg',{type:'task_started',turn_id:`turn-${id}`})+row('response_item',{type:'function_call',name:'exec_command',call_id:`call-${id}`,arguments:'{}'});
  const backend=spawn('child-a','backend')+row('event_msg',{type:'user_message',message:'inherited secret'},now-1000)+work('a');
  writeFileSync(path.join(sessions,'backend.jsonl'),backend);
  writeFileSync(path.join(sessions,'frontend.jsonl'),spawn('child-b','frontend')+work('b'));
  writeFileSync(path.join(sessions,'unknown.jsonl'),spawn('child-c','research')+work('c'));
  writeFileSync(path.join(sessions,'guardian.jsonl'),spawn('guardian','backend','guardian_review')+work('guard'));
  bridge.poll();
  assert.deepEqual(events.filter(e=>e.type==='AGENT_ASSIGNED').map(e=>e.to).sort(),['backend','frontend','helper']);
  assert.equal(events.find(e=>e.type==='AGENT_WORKING'&&e.source_session_id==='child-a').agent,'backend');
  assert.ok(events.filter(e=>e.source_session_id==='child-a').every(e=>e.session_id==='codex-root'&&e.parent_session_id==='root'));
  assert.equal(JSON.stringify(audit.read('codex-root')).includes('inherited secret'),false);
  appendFileSync(path.join(sessions,'frontend.jsonl'),row('event_msg',{type:'task_complete',turn_id:'turn-b',last_agent_message:'frontend ready'}));
  bridge.poll();
  appendFileSync(path.join(sessions,'backend.jsonl'),row('event_msg',{type:'task_complete',turn_id:'turn-a',last_agent_message:'backend ready'}));
  bridge.poll();
  assert.equal(events.filter(e=>e.type==='TASK_COMPLETE').length,0);
  assert.equal(events.filter(e=>e.type==='AGENT_DONE').length,2);
  assert.equal(ended.length,0);
  assert.equal(audit.read('codex-root').find(e=>e.type==='tool_call'&&e.source_session_id==='child-a').source_event_id,'call-a');
  const report=rounds(audit.read('codex-root'))[0];
  assert.equal(report.steps.find(s=>s.assigned.agent==='backend').result.output,'backend ready');
  assert.equal(report.steps.find(s=>s.assigned.agent==='frontend').result.output,'frontend ready');
  assert.ok(report.steps.find(s=>s.assigned.agent==='backend').finished);
  assert.match(exportMarkdown('codex-root',audit.read('codex-root')),/backend ready/);
  const count=audit.read('codex-root').length, eventCount=events.length;
  writeFileSync(path.join(sessions,'sidecar.jsonl'),backend+row('event_msg',{type:'task_complete',turn_id:'turn-a',last_agent_message:'backend ready'}));
  bridge.poll(); bridge=new CodexBridge(opts); bridge.poll();
  assert.equal(audit.read('codex-root').length,count); assert.equal(events.length,eventCount);
  appendFileSync(path.join(sessions,'root.jsonl'),row('event_msg',{type:'task_complete',turn_id:'root-turn',last_agent_message:'all done'}));
  bridge.poll();
  assert.equal(events.find(e=>e.type==='TASK_COMPLETE').agents,3);
  assert.deepEqual(ended,['codex-root']);
  appendFileSync(path.join(sessions,'root.jsonl'),row('event_msg',{type:'task_started',turn_id:'root-turn-2'}));
  bridge.poll();
  appendFileSync(path.join(sessions,'backend.jsonl'),row('event_msg',{type:'task_started',turn_id:'turn-a-2'}));
  bridge.poll();
  assert.equal(events.filter(e=>e.type==='AGENT_ASSIGNED'&&e.source_session_id==='child-a').length,2);
  assert.equal(bridge.status.activeChildren,2);
  assert.equal(audit.sessions().length,1); assert.equal(verify(audit.read('codex-root')).ok,true);
 } finally {rmSync(dir,{recursive:true,force:true});}
});
