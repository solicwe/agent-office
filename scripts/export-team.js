// Builds share/ from the roles in .claude/agents/, for friends who use the roles
// without Agent Office:  npm run export-team
//   share/TEAM_PROMPT.md   one prompt that makes any chat AI act as the whole team
//   share/AGENTS.md        the same team for tools that read AGENTS.md (Codex, Cursor, ...)
//   share/roles/<id>.md    each role alone, as plain instructions (no frontmatter)
//   share/claude-code/     the role files exactly as Claude Code reads them
// Run it after editing a role; `npm test` fails while share/ is out of date.
import { mkdirSync, writeFileSync, rmSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadAgents } from "../src/agents.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Every file share/ should contain: relative path -> content. */
export function buildShare(agentsDir = path.join(root, ".claude", "agents")) {
  const { agents, errors } = loadAgents(agentsDir);
  if (errors.length) throw new Error(`fix these role files first: ${errors.map((e) => `${e.file}: ${e.message}`).join("; ")}`);
  const files = {};
  const title = (a) => `${a.name} (${a.id})${a.role_title ? ` · ${a.role_title}` : ""}`;

  const roster = agents.map((a) => `- **${title(a)}**: ${a.description}`).join("\n");
  const roleBlocks = agents.map((a) => `### ${title(a)}\n\nWhen to use: ${a.description}\n\n${a.instructions.trim()}`).join("\n\n---\n\n");
  const team = `You lead a small software team. Each member below is a specialist role. You (the lead) read each request, pick only the roles it really needs, and run them.

## How to work on every request

1. **Plan the team.** Say in one or two lines which roles you will use, in what order, and why the others are not needed. Use the fewest roles that do the job well; a small, clear change may need just one.
2. **Run each chosen role in turn.** Start a section with the role's heading (for example "### Mia · Frontend Engineer") and answer strictly as that role, following its instructions below. Each role builds on what the earlier roles wrote.
3. **Finish with "### Final answer"**: the combined result for the user, the files or steps to apply, and anything still open.
4. **End every reply with a log block**, exactly in this form (valid JSON, inside a code block whose language is team-log). It is how the team's work is recorded, so never skip it:

\`\`\`team-log
{"request": "the user's request in one sentence", "order": "sequential", "roles": [{"id": "frontend", "why": "why this role was needed", "task": "what it was asked to do", "summary": "what it did or found, 1-3 sentences"}], "final": "the final answer in 1-3 sentences"}
\`\`\`

   Use the role ids from the list below. "order" is "parallel" only when the roles worked independently. If no role was needed, use an empty roles list.

If the user names a role ("ให้ frontend ช่วย..."), use that role. Reply in the user's language.

## The team

${roster}

## Role instructions

${roleBlocks}
`;
  files["TEAM_PROMPT.md"] = `<!-- Generated from .claude/agents by npm run export-team. Edit the roles there, not here. -->\n# Team prompt\n\n${team}`;
  files["AGENTS.md"] = `<!-- Generated from .claude/agents by npm run export-team. Edit the roles there, not here. -->\n# Agents\n\nThis project works as a team of roles. For every task, follow the process below.\n\n${team}`;

  for (const a of agents) {
    files[`roles/${a.id}.md`] = `<!-- Generated from .claude/agents/${a.file} by npm run export-team. -->\n# ${title(a)}\n\nWhen to use: ${a.description}\n\n${a.instructions.trim()}\n`;
    files[`claude-code/${a.file}`] = readFileSync(path.join(agentsDir, a.file), "utf8");
  }

  files["README.md"] = `<!-- Generated by npm run export-team. -->
# ใช้ role ของทีมโดยไม่ต้องเปิด Agent Office

ไฟล์ในโฟลเดอร์นี้สร้างอัตโนมัติจาก \`.claude/agents/\` (${agents.length} role: ${agents.map((a) => a.name).join(", ")}) ดาวน์โหลดจาก GitHub ไปใช้ได้เลย ไม่ต้องติดตั้งอะไร

## 1. ใช้ Claude Code (แนะนำ ได้ทีม agent จริง)

คัดลอกโฟลเดอร์ \`claude-code/\` ไปไว้ในโปรเจกต์ของคุณเป็น \`.claude/agents/\`

\`\`\`
โปรเจกต์ของคุณ/
  .claude/
    agents/
      pm.md  architect.md  frontend.md ...
\`\`\`

เปิด Claude Code ในโปรเจกต์นั้น พิมพ์ \`/agents\` เพื่อดูว่าเห็นครบไหม แล้วสั่งงานตามปกติ Claude จะเลือก role เอง หรือพิมพ์ชื่อ เช่น "ให้ reviewer ช่วยตรวจไฟล์นี้"

ไม่ต้องคัดลอก \`.claude/settings.json\` ของ repo นี้ (ไฟล์นั้นส่งข้อมูลให้ Agent Office ถ้าไม่ได้เปิดโปรแกรมก็ไม่ต้องใช้)

## 2. ใช้ claude.ai / ChatGPT / แชท AI ทั่วไป

แชททั่วไปเรียก agent แยกตัวไม่ได้ จึงใช้ \`TEAM_PROMPT.md\` ที่ให้ AI ตัวเดียวทำงานเป็นทั้งทีม: บอกก่อนว่าจะใช้ใคร แล้วตอบทีละ role จนได้คำตอบสุดท้าย

- **claude.ai Projects**: สร้าง Project แล้ววางเนื้อหา \`TEAM_PROMPT.md\` ในช่อง Project instructions ทุกแชทใน Project นั้นจะทำงานเป็นทีม
- **ChatGPT**: วางใน Custom instructions หรือสร้าง GPT แล้ววางในช่อง Instructions
- **แชทครั้งเดียว**: แปะเนื้อหาไฟล์เป็นข้อความแรก แล้วพิมพ์งานต่อท้าย

อยากได้แค่บางคน ใช้ไฟล์ใน \`roles/\` เช่นแปะ \`roles/reviewer.md\` แล้วขอให้ตรวจโค้ด

### ส่ง log จากแชท (Gemini, ChatGPT, claude.ai) ให้คนรวบรวม

ทุกคำตอบของ AI ที่ใช้ \`TEAM_PROMPT.md\` จะจบด้วยบล็อกโค้ด \`team-log\` (บอกว่าใช้ role ไหน ทำไม ทำอะไร คำตอบสุดท้าย)

1. คุยกับ AI ตามปกติ
2. คัดลอกทั้งบทสนทนา (หรือกด Share/Export แล้วคัดลอกข้อความ) เก็บเป็นไฟล์ .txt หรือ .md ก็ได้
3. ส่งให้คนที่เปิด Agent Office ไว้ คนนั้นกด **นำเข้า log จากแชท** ในแท็บ Audit log แล้ววางข้อความหรือเลือกไฟล์

log ที่นำเข้าจะขึ้นป้าย "นำเข้าจากแชท (AI รายงานเอง)" เพราะแชททั่วไปส่งข้อมูลการทำงานจริงออกมาไม่ได้ เราเชื่อได้แค่ว่า AI รายงานไว้แบบนั้น และนับจากตอนนำเข้า log จะถูกยึด hash ขึ้น GitHub แก้ย้อนหลังไม่ได้เหมือน log อื่น

ถ้า AI ลืมใส่บล็อก ให้พิมพ์ว่า "ใส่ team-log ด้วย"

## 3. ใช้ Codex, Cursor หรือเครื่องมือที่อ่าน AGENTS.md

คัดลอก \`AGENTS.md\` ไปไว้ที่โฟลเดอร์บนสุดของโปรเจกต์ เครื่องมือจะอ่านเองทุกครั้ง

## ต่างกันยังไง

| วิธี | ได้ agent แยกตัวจริง | ตัวการ์ตูน + audit log |
|---|---|---|
| Claude Code + Agent Office | ใช่ | ใช่ |
| Claude Code อย่างเดียว (ข้อ 1) | ใช่ | ไม่มี |
| แชททั่วไป / AGENTS.md (ข้อ 2, 3) | AI ตัวเดียวสวมบทแต่ละ role | log จาก team-log (AI รายงานเอง) นำเข้า Agent Office ได้ |

log ที่น่าเชื่อถือที่สุดสำหรับอาจารย์คือจาก Claude Code + Agent Office เพราะจับจากการทำงานจริง
`;
  return files;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, "share");
  const files = buildShare();
  rmSync(out, { recursive: true, force: true });
  for (const [rel, content] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(out, rel)), { recursive: true });
    writeFileSync(path.join(out, rel), content);
  }
  console.log(`share/ updated: ${Object.keys(files).length} files`);
}
